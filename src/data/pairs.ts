export function getPairBySlug(slug: string): ComparisonPair | undefined {
  return PAIRS.find(p => p.slug === slug);
}

export function getRelatedPairs(slug: string, category: string, limit = 4): ComparisonPair[] {
  return PAIRS.filter(p => p.slug !== slug && p.category === category).slice(0, limit);
}
